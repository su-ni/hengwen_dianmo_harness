# -*- coding: utf-8 -*-
"""写时抽取：把「用户说过的话」变成结构化记忆（第 9 章 D30）。

**为什么必须有这一层**
上一版只有 memory_add 一个工具，靠模型「想起来才调」。实测结果是：
聊了十几轮，记忆表一条没涨 —— 模型每轮都在忙着干活，谁也不会主动记账。
记忆系统于是成了个空壳：界面很好看，里面是空的。

**为什么抽的是「用户说的话」，不是模型的回答**
模型说的可能不准、可能被它自己后来的话推翻；用户亲口说的
（「我晚上效率高」「递归绕不出来」「3 月 15 号考试」）才是那个「他是谁」。
所以这一层只读用户消息，不读模型输出 —— 这是刻意的取舍，
宁可少记，不要记错。

**为什么是规则不是再调一次模型**
每轮多一次模型调用，成本翻倍、延迟翻倍，而这件事的准确率并不依赖语义理解：
目标/日期/时长/弱项都是很定型的说法。规则抽不准的宁可不记（少一条不致命），
抽错了才是真麻烦（界面上一堆假记忆，人会不再信这张表）。

规则没覆盖到的，留给模型用 memory_add 补 —— 两条路并存，不冲突。
"""
from __future__ import annotations

import re

# 每条规则：(类型, 正则, 权重, 是否整句存)
RULES = [
    # ---- 目标 / 考试（最重要的一类，时态说法多，覆盖要全）----
    ("goal", r"(专升本|考研|考公|四六级|教资|法考).{0,12}?(\d{4}|\d{1,2})\s*[年\-/\.]\s*(\d{1,2})?\s*[月\-/\.]?\s*(\d{1,2})?", 1.0, True),
    ("goal", r"(\d{4})\s*[年\-/\.]\s*(\d{1,2})\s*[月\-/\.]\s*(\d{1,2})\s*[号日]?.{0,10}(考试|专升本|笔试)", 1.0, True),
    ("goal", r"(明年|今年|后年).{0,8}(专升本|考研|考试)", 0.95, True),
    ("goal", r"目标(院校|学校|分数|是).{0,40}", 0.95, True),
    ("goal", r"想(考|上|报).{0,30}(大学|学院|学校|专业)", 0.9, True),

    # ---- 困难点 ----
    ("difficulty", r"(总是|老是|一直)(绕不出来|搞混|记不住|做不对|跟不上|听不懂)", 0.9, True),
    ("difficulty", r"(我的?弱项|不太会|不太懂|薄弱|搞不懂|没弄明白).{0,40}", 0.85, True),
    ("difficulty", r"(英语|数学|高数|政治|计算机).{0,12}(不好|很差|不行|拖后腿)", 0.85, True),

    # ---- 洞察（从事实归纳出来的判断，不是用户原话）----
    # 只有当用户自己说「看来 / 说明 / 总结」时才算 —— 那是他在下结论。
    ("insight", r"(看来|说明|总的来说|总结一下|应该是|大概是).{4,40}", 0.7, True),

    # ---- 偏好 / 作息 ----
    ("pref", r"(我)?(喜欢|习惯|更愿意|更爱)(先|看|听|做).{0,40}", 0.8, True),
    ("pref", r"(晚上|早上|凌晨|白天).{0,20}(效率最高|效率高|效率好|精神最好|精神好|学得进|状态最好)", 0.8, True),
    ("pref", r"(不喜欢|受不了|别|不要).{0,30}(一次问|问太多|太长)", 0.75, True),

    # ---- 计划变更（"改成"整句要留下，只留"每天150分钟"等于把变更说成了现状）----
    # 「每天」+「改成」要一起抓 —— 只说「改成 90 分钟」没头没尾，
    # 存进记忆里看不出改的是什么（实测抽出来的就是这种残句）。
    ("change", r"每天.{0,8}?(?:改成|调整为|变成).{0,12}?\d+\s*(?:分钟|小时|个词|道题)?", 0.95, True),
    # 单位可选：口语里「改成120」就是省了「分钟」，硬要求单位会漏掉最常见的那种说法
    ("change", r"把.{0,16}?\d+\s*(?:分钟|小时|个词|道题)?.{0,10}?(?:改成|调整为|变成).{0,12}?\d+\s*(?:分钟|小时|个词|道题)?", 0.95, True),
    ("change", r"(?:改成|调整为|变成).{0,24}?\d+\s*(?:分钟|小时|个词|道题)?", 0.9, True),
    ("change", r"每天.{0,10}?\d+\s*(?:分钟|小时|个词|道题)", 0.7, True),
]

# 一些「看着像但其实不是」的说法，抽到就丢
NOISE = re.compile(r"^(好的|可以|行|嗯|OK|继续|再说|不知道|随便)$", re.I)


def off_topic_text(t: str) -> bool:
    """太长的不抽：一句话说了 120 字以上，多半是在讲一件事的经过，
    不是关于「他是谁」的一句话。整段塞进记忆表，界面会很脏。"""
    return len(t) > 120


# 疑问句不是陈述。用户问「我的弱项是什么吗」，那是在**提问**，
# 不是在告诉你他的弱项 —— 抽出来存成事实，就成了系统自己编的记忆。
# 实测踩到过：库里多了一条 difficulty「我的弱项是什么吗」。
_QUESTION = re.compile(r"吗$|呢$|什么|怎么|如何|为什么|哪|多少|是不是|有没有|[?？]")

# 否定句同样不能当事实存。「我每天不是 150 分钟」抽出来存成
# 「每天不是150分钟」—— 这是一条**说它不是多少**的记忆，
# 存进库里既没用又容易被误读（实测抽过）。
# 注意不要把「说错了」算成否定 —— 它是在**认错**，后面跟的往往是真值。
_NEGATION = re.compile(r"不是|不对|并非|没有|不算")
# 自己先认错的话术，整段丢掉（"说错了"「记岔了」这类不是内容）
_APOLOGY = re.compile(r"说错了|记错了|记岔了|搞错了|不对不对")


def is_question(t: str) -> bool:
    return bool(_QUESTION.search((t or "").strip()))


def guess(text: str):
    """抽一轮：返回 [(kind, content, weight, rule_id), ...]

    同一条规则可能命中多次，只取最长的那个（最长 = 信息最全）。
    """
    t = (text or "").strip()
    if not t or NOISE.match(t) or off_topic_text(t):
        return []
    # 疑问句一律不抽：问题里出现的"弱项""目标"是**提问的对象**，不是答案。
    if is_question(t):
        return []
    # 否定说法不能直接存（「每天不是 150 分钟」存下来没有意义）。
    # 但**不能整句丢弃**：「不是 150，是 90」里后半句才是真值。
    # 做法是把含否定的那几段切掉，用剩下的部分去匹配。
    # 实测踩过：整句拦截导致「说错了，我每天不是 150 分钟，是 90 分钟」
    # 一个字都没抽到，等于它改主意这件事完全没被记住。
    if _NEGATION.search(t):
        # 把「不是 150 分钟」这种否定片段**挖掉**，不是整句丢弃。
        # 用正则整体替换：split 后重新拼会把上下文拆散，
        # 「每天不是 150 分钟改成 90 分钟」拆完两半都匹配不上（实测）。
        t = re.sub(r"不是[^，,。；;]*", " ", t)
        t = re.sub(r"并非[^，,。；;]*", " ", t)
        t = re.sub(r"不算[^，,。；;]*", " ", t)
        t = re.sub(r"\s+", " ", t).strip()
        if not t:
            return []
    hits = {}
    for idx, (kind, pat, w, whole) in enumerate(RULES):
        try:
            m = re.search(pat, t)
        except re.error:
            continue
        if not m:
            continue
        s = m.group(0).strip() if whole else (m.group(1) if m.groups() else m.group(0)).strip()
        if not s or len(s) < 4:
            continue
        key = kind
        # 同类型里只留一条：先比**规则优先级**（"改成"比"每天N分钟"更具体），再比长度。
        # 只比长度会让「每天150分钟」赢过「把150分钟改成120」——
        # 后者才是那条变更，前者只是它的一部分。
        old = hits.get(key)
        if old is None or (w, len(s)) > (old[2], len(old[1])):
            hits[key] = (kind, s, w, idx)
    return list(hits.values())


def split_sentences(text: str):
    """把一段话拆成句子 —— 一次输入里可能同时说了目标 + 弱项。"""
    t = (text or "").strip()
    if not t:
        return []
    # 逗号也要切：口语里「我的弱项是英语，晚上效率最高」是**两件事**，
    # 不切的话同类型合并逻辑会把其中一件吃掉（实测过）。
    parts = re.split(r"[。！？!?\n；;，,]+", t)
    return [p.strip() for p in parts if p and len(p.strip()) >= 4]


def extract(text: str):
    """整段分析的入口：剥认错话术 → 拆句 → 每句过规则 → 去重。

    返回 [(kind, content, weight), ...]，已按内容去重，权重取最高。
    """
    # 「说错了，我每天不是 150，是 90」—— 前半句是认错，不是内容。
    # 剥掉它，后面的"是 90 分钟"才有机会被看到（实测不剥就整段丢）。
    base_text = _APOLOGY.sub("，", str(text or ""))
    # 「不是 X，是 Y」是**同一个语义单元**（纠正），拆开两半都不成立：
    #   前半句只有否定 → 丢弃；
    #   后半句只剩「是 90 分钟」→ 没有主语，规则匹配不上。
    # 所以在拆句之前先把它整体压成 "X是Y" 的形式，
    # 让 change 规则能一眼看出「从什么改成什么」。
    base_text = re.sub(
        r"不是\s*([0-9]+[^，,。；;]*?)\s*[，,]\s*(?:而)?是\s*([0-9]+[^，,。；;]*)",
        r"改成 \2", base_text)
    seen = {}
    for sent in split_sentences(base_text):
        for kind, content, w, _idx in guess(sent):
            k = re.sub(r"\s+", "", content)
            if k in seen:
                if w > seen[k][1]:
                    seen[k] = (kind, max(w, seen[k][1]), content)
            else:
                seen[k] = (kind, w, content)
    # 整段兜底：只在分句时**一条都没抽到**才用。
    # 否则整段会再命中一遍，把分句出来的精确结果盖掉
    # （实测：「弱项是英语，晚上效率最高」整段命中 difficulty 就吃掉了 pref）。
    if not seen:
        for kind, content, w, _idx in guess(text):
            k = re.sub(r"\s+", "", content)
            seen[k] = (kind, w, content)
    out = []
    for _k, (kind, w, content) in seen.items():
        out.append((kind, content, round(w, 2)))
    # 去「包含关系」：分句后短句和整段都会命中，
    # 「我的弱项是英语完形填空」是「我的弱项是英语完形填空，晚上效率最高」的子串 ——
    # 留短的那个（分句后更精确，不会把两件事粘成一条）。
    kept = []
    for cur in out:
        dup = False
        for other in out:
            if other is cur:
                continue
            if cur[1] in other[1] and len(cur[1]) < len(other[1]):
                dup = True
                break
        if not dup:
            kept.append(cur)
    kept.sort(key=lambda x: -x[2])
    return kept[:4]         # 一轮最多记 4 条，多了说明这不是「关于他」的话
